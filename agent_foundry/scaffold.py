"""Scaffold — generates a new agent's starting files in seconds instead of
hand-wiring AgentConfig, a prompt file, and a topology from scratch. This is
what actually moves build time from days to hours: the architecture makes an
agent *possible* to build quickly, this module makes it *fast* to start.

    python -m agent_foundry.scaffold sales_agent --topology single --tools lookup_lead,send_email

writes prompts/sales_agent.md and agents/sales_agent.py — a runnable script with
TODOs marking the only things you actually need to fill in: the prompt's content
and each tool function's body. Everything else (gateways, guardrails, eval,
runtime, tracer) is already wired.
"""
