def create_agent(name: str, *, directory: str = ".", topology: str = "single", tools: list[str] | None = None) -> dict[str, str]:
    """Writes prompts/<name>.md and agents/<name>.py under `directory`. Returns the
    paths written. `topology` is currently informational (single-agent template);
    for supervisor/swarm/etc., copy this file's AGENT_TEMPLATE as a starting point
    — the four-line difference is which build_*_graph you call in orchestration.py."""
    tools = tools or []
    title = name.replace("_", " ").replace("-", " ").title()

    tool_lines = "\n".join(f"- {t}(...)" for t in tools) or "(none yet — TODO: add some)"
    prompts_dir = os.path.join(directory, "prompts")
    os.makedirs(prompts_dir, exist_ok=True)
    prompt_path = os.path.join(prompts_dir, f"{name}.md")
    with open(prompt_path, "w") as f:
        f.write(_PROMPT_TEMPLATE.format(title=title, tool_lines=tool_lines))

    tool_stubs = "".join(_TOOL_STUB_TEMPLATE.format(tool_name=t) for t in tools)
    tool_registrations = "".join(
        f'    tools.register(ToolSpec("{t}", "TODO: describe {t}", {{}}, {t}))\n' for t in tools
    ) or "    # TODO: tools.register(ToolSpec(...))\n"
    tool_names = ", ".join(f'"{t}"' for t in tools)

    agents_dir = os.path.join(directory, "agents")
    os.makedirs(agents_dir, exist_ok=True)
    agent_path = os.path.join(agents_dir, f"{name}.py")
    with open(agent_path, "w") as f:
        f.write(_AGENT_TEMPLATE.format(
            title=title, name=name, tool_stubs=tool_stubs,
            tool_registrations=tool_registrations, tool_names=tool_names,
        ))

    return {"prompt": prompt_path, "agent": agent_path}


def _main() -> None:
    parser = argparse.ArgumentParser(description="Scaffold a new Agent Foundry agent.")
    parser.add_argument("name", help="snake_case agent name, e.g. sales_agent")
    parser.add_argument("--directory", default=".", help="project root to write prompts/ and agents/ into")
    parser.add_argument("--topology", default="single", choices=["single"], help="currently only 'single' is templated")
    parser.add_argument("--tools", default="", help="comma-separated tool names, e.g. lookup_lead,send_email")
    args = parser.parse_args()

    tools = [t.strip() for t in args.tools.split(",") if t.strip()]
    paths = create_agent(args.name, directory=args.directory, topology=args.topology, tools=tools)
    print(f"wrote {paths['prompt']}")
    print(f"wrote {paths['agent']}")
    print(f"next: fill in the TODOs, set ANTHROPIC_API_KEY, then run python {paths['agent']}")


if __name__ == "__main__":
    _main()
